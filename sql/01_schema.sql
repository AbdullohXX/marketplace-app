BEGIN;
CREATE TABLE IF NOT EXISTS sellers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE, city varchar(80) NOT NULL,
  description text NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(80) NOT NULL UNIQUE, icon text NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id integer NOT NULL REFERENCES sellers(id),
  category_id integer NOT NULL REFERENCES categories(id),
  name varchar(120) NOT NULL, description text NOT NULL,
  price numeric(14,0) NOT NULL CHECK(price > 0 AND price <= 100000000),
  stock integer NOT NULL CHECK(stock >= 0),
  approved boolean NOT NULL DEFAULT false, active boolean NOT NULL DEFAULT true,
  icon text NOT NULL DEFAULT '📦', created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL, email varchar(254) NOT NULL UNIQUE,
  city varchar(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  address varchar(300) NOT NULL, total numeric(14,0) NOT NULL CHECK(total > 0),
  status text NOT NULL DEFAULT 'placed' CHECK(status IN ('placed','shipped','delivered','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS seller_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id),
  seller_id integer NOT NULL REFERENCES sellers(id),
  total numeric(14,0) NOT NULL CHECK(total > 0),
  status text NOT NULL DEFAULT 'placed' CHECK(status IN ('placed','shipped','delivered','cancelled')),
  UNIQUE(order_id,seller_id), UNIQUE(id,order_id,seller_id)
);
-- Order items form the many-to-many relation between orders and products.
CREATE TABLE IF NOT EXISTS order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id),
  seller_order_id integer NOT NULL,
  seller_id integer NOT NULL REFERENCES sellers(id),
  product_id integer NOT NULL REFERENCES products(id),
  quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 99),
  unit_price numeric(14,0) NOT NULL CHECK(unit_price > 0),
  FOREIGN KEY(seller_order_id,order_id,seller_id) REFERENCES seller_orders(id,order_id,seller_id),
  UNIQUE(order_id, product_id)
);
CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL UNIQUE REFERENCES orders(id),
  amount numeric(14,0) NOT NULL CHECK(amount > 0),
  method text NOT NULL DEFAULT 'cash_on_delivery' CHECK(method = 'cash_on_delivery'),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','paid','refunded'))
);
CREATE TABLE IF NOT EXISTS payouts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_order_id integer NOT NULL UNIQUE REFERENCES seller_orders(id),
  amount numeric(14,0) NOT NULL CHECK(amount > 0),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','paid'))
);
CREATE INDEX IF NOT EXISTS products_seller_idx ON products(seller_id);
CREATE INDEX IF NOT EXISTS products_category_idx ON products(category_id);
CREATE INDEX IF NOT EXISTS orders_customer_idx ON orders(customer_id);
CREATE INDEX IF NOT EXISTS seller_orders_seller_idx ON seller_orders(seller_id);
CREATE INDEX IF NOT EXISTS items_product_idx ON order_items(product_id);
CREATE INDEX IF NOT EXISTS items_seller_order_idx ON order_items(seller_order_id);
CREATE INDEX IF NOT EXISTS items_order_idx ON order_items(order_id);
CREATE INDEX IF NOT EXISTS items_seller_idx ON order_items(seller_id);
CREATE OR REPLACE VIEW seller_sales AS
SELECT s.id, s.name, s.city, count(so.id)::integer AS order_count,
       coalesce(sum(so.total) FILTER(WHERE so.status <> 'cancelled'),0) AS revenue
FROM sellers s LEFT JOIN seller_orders so ON so.seller_id=s.id GROUP BY s.id;
CREATE TABLE IF NOT EXISTS checkout_requests (
  request_key uuid PRIMARY KEY,
  fingerprint text NOT NULL,
  response jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMIT;
